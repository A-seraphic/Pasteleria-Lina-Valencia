-- ── Dueños con acceso al panel ─────────────────────────────────────────────────
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

drop policy if exists "admins se ven a sí mismos" on public.admins;
create policy "admins se ven a sí mismos" on public.admins
  for select using (public.is_admin());

-- ── Tablas del catálogo ────────────────────────────────────────────────────────
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  tagline text default '',
  short_desc text default '',
  price text default '',
  tag text default '',
  img text default '',
  description text default '',
  details jsonb not null default '[]',
  visible boolean not null default true,
  sort int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  name text not null,
  subtitle text default '',
  description text default '',
  img text default '',
  price text default '',
  badge text default '',
  visible boolean not null default true,
  sort int not null default 0,
  ar boolean not null default false,
  portion_ids jsonb not null default '[]',
  options jsonb not null default '{}',
  base_price numeric not null default 0,
  lead_days int not null default 0,
  receipt_note text not null default '',
  custom_fields jsonb not null default '[]',
  created_at timestamptz not null default now()
);

create table if not exists public.options (
  id bigint generated by default as identity primary key,
  kind text not null,
  name text not null,
  visible boolean not null default true,
  sort int not null default 0,
  price_extra numeric not null default 0,
  description text not null default ''
);

create table if not exists public.portions (
  id bigint generated by default as identity primary key,
  label text not null,
  people text default '',
  diameter_cm numeric not null default 20,
  height_cm numeric not null default 10,
  tiers int not null default 1 check (tiers between 1 and 4),
  slices int not null default 8 check (slices between 1 and 120),
  sort int not null default 0,
  price_extra numeric not null default 0
);

-- Ajustes del negocio, del recibo y de las especializaciones (clave → JSON)
create table if not exists public.settings (
  key text primary key,
  value jsonb not null default '{}',
  updated_at timestamptz not null default now()
);

-- ── Seguridad: todos leen, solo los dueños escriben ────────────────────────────
do $$
declare t text;
begin
  foreach t in array array['categories', 'products', 'options', 'portions', 'settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "lectura pública" on public.%I', t);
    execute format('drop policy if exists "dueños escriben" on public.%I', t);
    execute format('create policy "lectura pública" on public.%I for select using (true)', t);
    execute format(
      'create policy "dueños escriben" on public.%I for all using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

-- ── Fotos: bucket público, solo los dueños suben o borran ─────────────────────
insert into storage.buckets (id, name, public)
values ('catalogo', 'catalogo', true)
on conflict (id) do update set public = true;

drop policy if exists "dueños suben fotos" on storage.objects;
drop policy if exists "dueños editan fotos" on storage.objects;
drop policy if exists "dueños borran fotos" on storage.objects;
create policy "dueños suben fotos" on storage.objects
  for insert with check (bucket_id = 'catalogo' and public.is_admin());
create policy "dueños editan fotos" on storage.objects
  for update using (bucket_id = 'catalogo' and public.is_admin());
create policy "dueños borran fotos" on storage.objects
  for delete using (bucket_id = 'catalogo' and public.is_admin());

